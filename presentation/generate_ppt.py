MUTED = RGBColor(0x9A, 0xA4, 0xB2)
WHITE = RGBColor(0xEC, 0xEF, 0xF3)

prs = Presentation()
prs.slide_width = Inches(13.333)
prs.slide_height = Inches(7.5)
BLANK = prs.slide_layouts[6]
SW, SH = prs.slide_width, prs.slide_height


def fill(slide, color=BG):
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = color


def box(slide, l, t, w, h, color):
    from pptx.enum.shapes import MSO_SHAPE
    shp = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, l, t, w, h)
    shp.fill.solid()
    shp.fill.fore_color.rgb = color
    shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def text(slide, l, t, w, h, runs, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, sp_after=6):
    tb = slide.shapes.add_textbox(l, t, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    first = True
    for item in runs:
        s = item.get("text", "")
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.alignment = item.get("align", align)
        p.space_after = Pt(item.get("sp_after", sp_after))
        p.space_before = Pt(item.get("sp_before", 0))
        for seg in (item["segs"] if "segs" in item else [{"t": s, **item}]):
            r = p.add_run()
            r.text = seg["t"]
            r.font.size = Pt(seg.get("size", item.get("size", 18)))
            r.font.bold = seg.get("bold", item.get("bold", False))
            r.font.italic = seg.get("italic", item.get("italic", False))
            r.font.name = seg.get("font", item.get("font", "Segoe UI"))
            r.font.color.rgb = seg.get("color", item.get("color", WHITE))
    return tb


def bullets(slide, l, t, w, h, items, size=18, color=WHITE, gap=8):
    tb = slide.shapes.add_textbox(l, t, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    for i, it in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        lvl = it[0] if isinstance(it, tuple) else 0
        txt = it[1] if isinstance(it, tuple) else it
        p.level = lvl
        r = p.add_run()
        r.text = ("•  " if lvl == 0 else "–  ") + txt
        r.font.size = Pt(size - 2 * lvl)
        r.font.name = "Segoe UI"
        r.font.color.rgb = color
    return tb


def header(slide, kicker, title):
    box(slide, 0, 0, SW, Inches(1.15), CARD)
    box(slide, 0, Inches(1.15), SW, Pt(3), ACCENT)
    text(slide, Inches(0.5), Inches(0.12), Inches(12), Inches(1.0), [
        {"text": kicker, "size": 12, "bold": True, "color": ACCENT, "sp_after": 0},
        {"text": title, "size": 26, "bold": True, "color": WHITE, "sp_after": 0},
    ])


def footer(slide, n):
    text(slide, Inches(0.4), Inches(7.05), Inches(9), Inches(0.4),
         [{"text": "SQLi Defence Lab · DAS PE4 · SQL Injection with Protection", "size": 10, "color": MUTED}])
    text(slide, Inches(12.2), Inches(7.05), Inches(0.9), Inches(0.4),
         [{"text": str(n), "size": 10, "color": MUTED, "align": PP_ALIGN.RIGHT}])


def picture_card(slide, path, l, t, w):
    if os.path.exists(path):
        pic = slide.shapes.add_picture(path, l, t, width=w)
        pic.line.color.rgb = RGBColor(0x2A, 0x30, 0x3A)
        pic.line.width = Pt(1)
        return pic
    else:
        ph = box(slide, l, t, w, Inches(3.2), CARD)
        text(slide, l, t + Inches(1.4), w, Inches(0.5),
             [{"text": "[screenshot: %s]" % os.path.basename(path), "size": 14,
               "color": MUTED, "align": PP_ALIGN.CENTER}])
        return ph


N = 0
def newslide():
    global N
    N += 1
    s = prs.slides.add_slide(BLANK)
    fill(s)
    return s


